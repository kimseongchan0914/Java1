package JavaClass;

public class Switch4Demo {
    public static void main(String[] args) {
        int number = 3;

        switch (number) {
            case 1:
                System.out.println("*");
                break;
            case 2:
                System.out.println("*");
                break;
            case 3:
                System.out.println("*");
                break;
            default:
                System.out.println("*");
        }
    }
}